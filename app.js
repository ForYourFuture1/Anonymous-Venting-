function initThemeToggle(){
  const stored = localStorage.getItem('majlis_theme');
  const theme = stored || (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
  document.documentElement.setAttribute('data-theme', theme);

  const btn = document.createElement('button');
  btn.type = 'button';
  btn.className = 'theme-toggle';
  btn.setAttribute('aria-label', 'تبديل الوضع الليلي والنهاري');
  btn.innerHTML = theme === 'dark' ? SUN_ICON : MOON_ICON;
  btn.addEventListener('click', ()=>{
    const next = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    document.documentElement.setAttribute('data-theme', next);
    localStorage.setItem('majlis_theme', next);
    btn.innerHTML = next === 'dark' ? SUN_ICON : MOON_ICON;
  });
  document.body.appendChild(btn);
}
if(document.readyState === 'loading'){
  document.addEventListener('DOMContentLoaded', initThemeToggle);
}else{
  initThemeToggle();
}

